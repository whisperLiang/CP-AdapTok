PLAN = OUTPUT / "pilot_plan.json"
WINDOW = 4


def make_training_plan(run, catalog):
    old = json_at(TRAIN_PLAN)
    videos = sorted(catalog.rows)
    original = make_plans(catalog, C1Run("sparse-rfsq", SEED, UPDATES, WINDOW, late_gop=True))
    if videos != old["videos"] or original != old["windows"]:
        raise RuntimeError("Train split or original W1 supervised frame inventory differs")
    windows = []
    for step, w in enumerate(original, 1):
        if w["length"] - w["phase"] != WINDOW:
            raise RuntimeError("W1 training inventory does not contain four supervised frames")
        seed = 100_000 * SEED + step
        budgets_rng = np.random.default_rng(seed)
        crop_rng = torch.Generator().manual_seed(seed)
        start = w["start"] + w["phase"]
        row = catalog.rows[videos[w["source"]]]
        windows.append({"source": w["source"], "start": start, "length": WINDOW, "rng_seed": seed,
                        "w1_gop_offset": w["phase"], "w1_gop_start": w["start"],
                        "frame_sha256": [f["sha256"] for f in row["frame_hashes"][start:start + WINDOW]],
                        "budgets": [list(budgets_for(i == 0, budgets_rng)) for i in range(WINDOW)],
                        "crops_yx": [[list(yx) for yx in crop_plan(1080, 1920, crop_rng)] for _ in range(WINDOW)]})
    plan = {"videos": videos, "windows": windows, "w1_plan_sha256": file_hash(TRAIN_PLAN),
            "w1_strict_training_comparator": False,
            "history": "Four W1 supervised source frames per update, starting a fresh I/P/P/P chain. "
                       "I/P-dependent K is regenerated by the W1 schedule using the actual frame type.",
            "gop_warmup_frames": 0, "holdout": run.lock["holdout"], "milestones": list(MILESTONES)}
    create_record(PLAN, plan)
    return plan


class Trainer(W1Trainer):
    def __init__(self, run, cases, arm):
        self.codec, self.fits, self.cases = run.codec, run.inputs.fits, cases
        self.model = create_model(arm, "cuda")
        self.receiver = DecoderReceiver(SIGMA, self.model)
        loss = run.provenance["w1"]["loss"]
        if loss["latent_anchor"] != ANCHOR_WEIGHT or loss["reference"] != REFERENCE_WEIGHT:
            raise RuntimeError("reference or anchor weights differ from the reused W1 objective")
        self.loss_weights = {k: v for k, v in loss.items() if k not in {"latent_anchor", "reference"}}
        self.objective = ReconstructionLoss(self.loss_weights).cuda().to(memory_format=torch.channels_last)
        options = dict(run.provenance["w1_optimizer"])
        if options.pop("decoupled_weight_decay") is not True:
            raise RuntimeError("expected W1 AdamW optimizer")
        options["betas"] = tuple(options["betas"])
        self.optimizer = torch.optim.AdamW(self.model.parameters(), **options)

    def update(self, clip, window, step, weights):
        row = self.step(clip, 0, step, diagnose=step % DIAG_EVERY == 0)
        frames = row["frames"]
        if (row["rng_seed"] != window["rng_seed"] or len(frames) != WINDOW
                or [list(f["budgets"]) for f in frames] != window["budgets"]
                or [f["kind"] for f in frames] != ["I", "P", "P", "P"]
                or [f["frame"] for f in frames] != list(range(WINDOW))
                or not all(f["state_sync"] for f in frames)):
            raise RuntimeError("pilot changed the preregistered four-frame training schedule")
        row.update(source=window["source"], start=window["start"],
                   gradient_clipped=row["gradient_norm"] + 1e-6 > 1.0, nan_or_inf=False)
        gradient = row["gradient_diagnostics"]
        if gradient is not None:
            raw = gradient.pop("norms")
            coefficients = {"mse": weights["mse"], "lpips": weights["lpips"], "anchor": weights["latent_anchor"]}
            weighted = {k: v * coefficients[k] for k, v in raw.items()}
            gradient.update(raw_norms=raw, weighted_norms=weighted,
                            weighted_lpips_to_mse=weighted["lpips"] / weighted["mse"] if weighted["mse"] else None)
        return row


def checkpoint_path(arm, step):
    return WEIGHTS / arm / f"seed{SEED}/step_{step:04d}.pt"


def optimizer_groups(state):
    return [{k: v for k, v in group.items() if k != "params"} for group in state["param_groups"]]


def resume_state(path, trainer, identity, windows):
    state = torch.load(path, weights_only=True, map_location="cpu")
    step = state["step"]
    if (state["identity"] != identity or step not in range(0, UPDATES + 1, DIAG_EVERY)
            or step != len(state["updates"])
            or state["next_window"] != (windows[step] if step < UPDATES else None)):
        raise RuntimeError(f"checkpoint does not match seed, model, step, plan, loss or frozen assets: {path}")
    if any(r["step"] != i or r["rng_seed"] != w["rng_seed"] or r["start"] != w["start"] or r["source"] != w["source"]
           for i, (r, w) in enumerate(zip(state["updates"], windows), 1)):
        raise RuntimeError(f"checkpoint training prefix differs: {path}")
    stored = state["optimizer"]
    if optimizer_groups(stored) != optimizer_groups(trainer.optimizer.state_dict()):
        raise RuntimeError(f"checkpoint AdamW configuration differs: {path}")
    slots = stored["state"]
    parameters = stored["param_groups"][0]["params"]
    valid_slots = (not slots) if step == 0 else (
        slots.keys() == set(parameters) and all(entry["step"].item() == step for entry in slots.values()))
    if not valid_slots or sorted(map(int, state["holdout"])) != [n for n in MILESTONES if n <= step]:
        raise RuntimeError(f"checkpoint optimizer steps or milestone records differ: {path}")
    trainer.model.load_state_dict(state["model"], strict=True)
    trainer.optimizer.load_state_dict(stored)
    return state["updates"], state["holdout"]


@torch.no_grad()
def score_holdout(run, trainer, clips):
    rows = {k: [] for k in FOCUS}
    for clip in clips:
        pair = CausalPair()
        for i, image in enumerate(clip):
            frame = pair.advance(run.codec, image, i, trainer.cases, trainer.receiver)
            case = trainer.cases[frame.sample.frame_type]
            for k in rows:
                latent = trainer.receiver(case, run.codec.backbone, frame.context, frame.payload[:, :k])
                rgb, _ = run.codec.backbone.decode_aligned(latent, frame.context)
                mse = F.mse_loss(rgb, frame.sample.rgb).item()
                if not math.isfinite(mse):
                    raise RuntimeError("Train holdout produced nonfinite distortion")
                rows[k].append({"mse": mse})
    return {str(k): distortion_summary(group) for k, group in rows.items()}


def persist(trainer, arm, identity, windows, updates, holdout, resume):
    step = len(updates)
    state = {"identity": identity, "step": step, "next_window": windows[step] if step < UPDATES else None,
             "updates": updates, "holdout": holdout, "model": trainer.model.state_dict(),
             "optimizer": trainer.optimizer.state_dict()}
    path = checkpoint_path(arm, step)
    if step in MILESTONES:
        save_checkpoint(path, state)
        print(f"{arm} step {step} saved", flush=True)
    else:
        save_checkpoint(resume, state)


def restore_latest(trainer, arm, identity, windows, resume):
    milestones = [checkpoint_path(arm, step) for step in MILESTONES if checkpoint_path(arm, step).is_file()]
    if resume.is_file():
        # Read the progress checkpoint's step before choosing the newer, self-contained snapshot.
        entry = torch.load(resume, weights_only=True, map_location="cpu")
        mile = max((int(p.stem.split("_")[1]) for p in milestones), default=-1)
        if entry["step"] > mile:
            return resume_state(resume, trainer, identity, windows)
    return resume_state(milestones[-1], trainer, identity, windows) if milestones else ([], {})


def verify_checkpoints(arm, record):
    for step in MILESTONES:
        path = checkpoint_path(arm, step)
        if record["checkpoints_sha256"][str(step)] != file_hash(path):
            raise RuntimeError(f"checkpoint failed SHA256 validation: {path}")
        data = torch.load(path, weights_only=True, map_location="cpu")
        if data["step"] != step or data["identity"] != record["identity"] or len(data["updates"]) != step:
            raise RuntimeError(f"invalid milestone step or identity: {path}")
        if not all(torch.isfinite(p).all() for p in data["model"].values()):
            raise RuntimeError(f"invalid model tensor: {path}")


def train_arm(run, train, cases, plan, clips, arm):
    trainer = Trainer(run, cases, arm)
    weights = run.provenance["w1"]["loss"]
    identity = {
        "arm": arm, "name": ARMS[arm], "seed": SEED, "steps": UPDATES, "supervised_frames": WINDOW,
        "burn_in_frames": 0, "init_sha256": tensor_digest(trainer.model), "loss": weights,
        "optimizer": run.provenance["w1_optimizer"], "scheduler": None, "scheduler_state": None,
        "gradient_clip_max_norm": 1.0, "plan_sha256": file_hash(PLAN), "provenance_sha256": file_hash(PROVENANCE),
        "tested_source_sha256": file_hash(TESTS), "trainer_source_sha256": file_hash(__file__),
        "architecture": {name: list(param.shape) for name, param in trainer.model.named_parameters()},
    }
    report = OUTPUT / f"pilot_train_{arm}.json"
    if report.is_file():
        record = json_at(report)
        if record["identity"] != identity:
            raise RuntimeError(f"completed {arm} uses a different training identity")
        verify_checkpoints(arm, record)
        print(f"{arm} already finished {record['steps']} updates", flush=True)
        return
    windows = plan["windows"]
    resume = checkpoint_path(arm, 0).with_name("progress.pt")
    updates, holdout = restore_latest(trainer, arm, identity, windows, resume)
    if not holdout:
        holdout["0"] = score_holdout(run, trainer, clips)
        persist(trainer, arm, identity, windows, updates, holdout, resume)
    pending = windows[len(updates):]
    torch.cuda.reset_peak_memory_stats()
    for clip, window in zip(run.reader.training_windows(train, pending), pending, strict=True):
        step = len(updates) + 1
        start = time.perf_counter()
        row = trainer.update(clip, window, step, weights)
        updates.append(row | {"seconds": time.perf_counter() - start, "peak_cuda_mib": memory()})
        if step in MILESTONES:
            holdout[str(step)] = score_holdout(run, trainer, clips)
        if step % DIAG_EVERY == 0:
            persist(trainer, arm, identity, windows, updates, holdout, resume)
            print(f"{arm} {step}/{UPDATES} · loss={row['loss']:.6f} · {updates[-1]['seconds']:.2f} s/update", flush=True)
    observed = [r["step"] for r in updates if r["gradient_diagnostics"] is not None]
    if len(updates) != UPDATES or observed != list(range(DIAG_EVERY, UPDATES + 1, DIAG_EVERY)):
        raise RuntimeError("pilot did not finish exactly 500 updates and ten gradient diagnostics")
    record = {
        "identity": identity, "steps": len(updates), "updates": updates, "train_holdout": holdout,
        "checkpoints_sha256": {str(step): file_hash(checkpoint_path(arm, step)) for step in MILESTONES},
        "seconds": sum(r["seconds"] for r in updates), "peak_cuda_mib": max(r["peak_cuda_mib"] for r in updates),
        "clipped_updates": sum(r["gradient_clipped"] for r in updates), "integrity": run.verify_integrity(),
    }
    verify_checkpoints(arm, record)
    write_json(report, record)
    resume.unlink(missing_ok=True)


def run_training(run):
    require_phase1()
    catalog = run.reader.open("train")
    train = training_catalog(catalog, run.lock["holdout"])
    plan = make_training_plan(run, train)
    holdout = [run.reader.read(catalog, r["video"], r["start"], r["frames"]) for r in plan["holdout"]]
    cases = run.inputs.cases("SP-1", run.lock["keys"]["SP-1"])
    for arm in ARMS:
        train_arm(run, train, cases, plan, holdout, arm)
    if run.reader.counts["validation"]:
        raise RuntimeError("Validation opened during pilot training")
