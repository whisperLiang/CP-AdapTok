"""Generate gate evidence and the Chinese report solely from raw JSON artifacts."""

import argparse
import json

from aip_vtok.evaluation.gates import assess_gate0
from aip_vtok.evaluation.report_stage1 import (
    color_section,
    diagnosis_section,
    engineering_section,
    intervention_section,
    quality_section,
)
from aip_vtok.evaluation.report_stage1 import status as stage1_status
from aip_vtok.runtime import file_hash, load_config, resolve, write_json


def load_json(path):
    return json.loads(resolve(path).read_text())


def collect(config):
    directory = resolve(config["output"])
    baseline = load_json(directory / "baseline.json")
    trials = []
    for path in sorted(directory.glob("projector_w*/evaluation.json")):
        trial = load_json(path)
        trial["artifact_path"] = str(path.relative_to(resolve(".")))
        trials.append(trial)
    result = {
        "gate": 0,
        "baseline": baseline,
        "projector_trials": trials,
        **assess_gate0(baseline, trials, config["limits"]),
    }
    result["source_sha256"] = {
        str(p.relative_to(resolve("."))): file_hash(p)
        for p in [
            directory / "baseline.json",
            directory / "calibration.json",
            *sorted(directory.glob("projector_w*/evaluation.json")),
        ]
    }
    result["later_gates"] = {
        "1": {"status": stage1_status(directory)},
        "2": {"status": "not_run", "reason": "requires Gate 1 quality release"},
        "3": {"status": "not_run", "reason": "requires Gate 2 release"},
    }
    return result


def table_rows(result, native):
    rows = ["| 路径 | PSNR 全局 MSE / dB | 逐帧 PSNR 均值 / dB |", "|---|---:|---:|"]
    for name, summary in [("官方实际码流", native["summary"]), *result["baseline"].items()]:
        rows.append(f"| {name} | {summary['psnr_global_mse']:.6f} | {summary['psnr_frame_mean']:.6f} |")
    for trial in result["projector_trials"]:
        s = trial["summary"]
        rows.append(f"| {trial['mode']} | {s['psnr_global_mse']:.6f} | {s['psnr_frame_mean']:.6f} |")
    return rows


def reference_rows(result):
    rows = [
        "| 投影器 | 相对对齐 R0 掉点 / dB | I 均值 / ms | P 均值 / ms | P P95 / ms |",
        "|---|---:|---:|---:|---:|",
    ]
    r0 = result["baseline"]["r0_aligned"]["psnr_global_mse"]
    for t in result["projector_trials"]:
        timing = t["projector_latency"]
        rows.append(
            f"| {t['mode']} | {r0 - t['summary']['psnr_global_mse']:.6f} | "
            f"{timing['I']['mean_ms']:.6f} | {timing['P']['mean_ms']:.6f} | "
            f"{timing['P']['p95_ms']:.6f} |"
        )
    return rows


def render_report(config, result):
    directory = resolve(config["output"])
    native = load_json(directory / "native_bitstream_control.json")
    calibration = load_json(directory / "calibration.json")
    audit = load_json(directory / "audit.json")
    status = "通过" if result["passed"] else "熔断，禁止进入 Gate 1–3"
    v = config["validation"]
    lines = [
        "# AIP-VTok 实测技术报告",
        "",
        "<!-- Generated by python -m aip_vtok.evaluation.report; do not edit numbers. -->",
        "",
        f"当前状态：**Gate 0 {status}；{stage1_status(directory)}**。尚未启用完整渐进二进制编解码器。",
        "",
        f"基线提交 `{audit['base_commit']}`，开发分支 `{audit['branch']}`。官方源码与旧生产包无差异。",
        "",
        f"数据：`{v['video']}`，原生 `{config['geometry']}`，连续 `{v['frames']}` 帧，QP `{config['qp']}`，GOP `{config['gop']}`。"
        "训练、校准仅使用 manifest 的 train；封存测试仅检查元数据，未读取图像。该结果不代表完整验证集。",
        "",
        "## Q1：尺度、对齐与参考闭环",
        "",
        "DMCI 连续直通保留 `q_scale_y_enc × q_scale_y_dec`。原生连续 R0 和对齐 R0 均绕过量化与熵编码；"
        "官方实际码流单列，三者不混用。P 帧全部在本路径自己的闭环历史下编码。",
        "",
        *table_rows(result, native),
        "",
        f"I 的 PCA 保留训练集方差比例 `{calibration['statistics']['retained_variance']:.9f}`。"
        "256→128→256 仅对子空间可逆，不能宣称任意输入无损；原生验证误差已计入对齐 R0。",
        "",
        *reference_rows(result),
        "",
        "延迟为 H100 上 FP32 eager / channels_last，CUDA Events、独立 I/P 头预热后计时。"
        "这只是参考投影模块的延迟，不能换算成完整编解码 FPS。",
        "",
        "投影训练使用自己提交的历史。监督目标来自同一个 frozen context 下的官方 Decoder 参考特征，"
        "没有异历史 P-latent 蒸馏。I 头输出 192 通道，P 头输出 256 通道；评估每帧仅一次 RGB 重建，"
        "提交投影参考不再执行 Decoder。",
        "",
        "门槛及判定：",
        "",
        "```json",
        json.dumps(
            {k: result[k] for k in ("r0_passed", "reference_passed", "passed", "limits")},
            ensure_ascii=False,
            indent=2,
        ),
        "```",
        "",
        *quality_section(directory),
        *intervention_section(directory),
        *color_section(directory),
        *diagnosis_section(directory),
        *engineering_section(directory),
        "## Q4：真实码流",
        "",
        f"官方基线实际 SPS/IP 码流为 `{native['bpp']:.9f}` bpp。AIP-VTok 已使用真实 FSQ ID 与 Tier 扫描，rANS 二进制封包尚未启用，"
        "其 bpp、Tier 占比、BD-Rate 均为未测，未制造空白 CSV 冒充已完成实验。",
        "",
        "## Q5：端到端速度",
        "",
        "未运行 Gate 3，Sender/Receiver/顺序联合 FPS 和完整模块分解均未测。",
        "",
        "## 复现与证据",
        "",
        "```bash",
        "bash scripts/aip_vtok/run_gate0.sh",
        "```",
        "",
        "主证据：`results/aip_vtok/gate0_backbone_and_ref.json`；逐帧数据在 `r0_*/rollout.json`、"
        "`projector_w*/evaluation.json`；训练日志和可恢复 checkpoint 均保留。完整原尺寸 PNG 与局部裁剪在对应路径目录。",
        "",
        "测试与隔离审计：`results/aip_vtok/tests/`、`results/aip_vtok/audit.json`。未通过的质量 Gate 不会被代码测试通过替代。",
        "",
    ]
    return "\n".join(lines)


def build(config):
    result = collect(config)
    write_json(resolve(config["output"]) / "gate0_backbone_and_ref.json", result)
    resolve("docs/aip_vtok_report.md").write_text(render_report(config, result))
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/aip_vtok/gate0.yaml")
    parser.add_argument("--require-pass", action="store_true")
    args = parser.parse_args()
    result = build(load_config(args.config))
    print(json.dumps({k: result[k] for k in ("passed", "r0_passed", "reference_passed", "decision")}))
    if args.require_pass and not result["passed"]:
        raise SystemExit(2)


if __name__ == "__main__":
    main()
