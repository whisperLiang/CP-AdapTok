"""Summarize actual artifacts and record explicit blocked gates, without placeholders."""

import json
import subprocess
import xml.etree.ElementTree as ET

from aip_vtok.runtime import ROOT, file_hash, resolve, write_json


def read(name):
    return json.loads((resolve("results/aip_vtok") / name).read_text())


def test_counts(name):
    root = ET.parse(resolve("results/aip_vtok/tests") / name).getroot()
    return {
        key: sum(int(s.get(key, 0)) for s in root.iter("testsuite"))
        for key in ("tests", "failures", "errors", "skipped")
    }


def checkpoints():
    names = (
        "alignment.pt",
        "projector_w128/latest.pt",
        "gate1_smoke/latest.pt",
        "gate1_seed1/latest.pt",
        "gate1_seed2/latest.pt",
    )
    return {
        name: {
            "sha256": file_hash(resolve("checkpoints/aip_vtok") / name),
            "bytes": (resolve("checkpoints/aip_vtok") / name).stat().st_size,
        }
        for name in names
    }


def main():
    protected = ("cp_adaptok", "adaptok_hr", "third_party", "experiments/fixed2048", "results/fixed2048")
    diff = subprocess.check_output(
        ["git", "diff", "630e814", "--name-only", "--", *protected], cwd=ROOT, text=True
    )
    if diff:
        raise RuntimeError(f"protected files changed: {diff}")
    audit = read("audit.json")
    weights_equal = {
        key: file_hash(audit["config"][key]) == value for key, value in audit["weights_sha256"].items()
    }
    g0, g1 = read("gate0_backbone_and_ref.json"), read("gate1_decision.json")
    result = {
        "branch": "experiment/aip-vtok",
        "gate0_passed": g0["passed"],
        "gate1_passed": g1["passed"],
        "gate2_status": "not_run_due_to_gate1_failure",
        "gate3_status": "not_run_due_to_gate1_failure",
        "regression_tests": test_counts("all_regression.xml"),
        "current_aip_tests": test_counts("aip_current.xml"),
        "protected_diff": diff,
        "official_weights_equal_to_start": weights_equal,
        "checkpoints": checkpoints(),
        "gpu_resume": read("checkpoint_gpu_replay.json"),
        "reference_cache": read("reference_cache_equivalence.json"),
        "seed2_recheck": read("evaluation_recheck.json"),
        "research_steps": {
            "projector": read("projector_w128/training.json")["steps"],
            "smoke": read("gate1_smoke/training.json")["history"][-1]["step"],
            "seed1": read("gate1_seed1/training_complete.json")["steps"],
            "seed2": read("gate1_seed2/training_complete.json")["steps"],
        },
        "source_sha256": {
            str(p.relative_to(ROOT)): file_hash(p)
            for p in [
                *sorted((ROOT / "aip_vtok").rglob("*.py")),
                *sorted((ROOT / "configs/aip_vtok").glob("*.yaml")),
                ROOT / "pyproject.toml",
            ]
        },
    }
    write_json("results/aip_vtok/final_summary.json", result)
    write_json("results/aip_vtok/checkpoints_manifest.json", result["checkpoints"])
    log = resolve("docs/aip_vtok_work_log.md")
    prefix = log.read_text().split("<!-- AIP_AUTOGENERATED_FINAL -->")[0].rstrip()
    summary = [
        "",
        "<!-- AIP_AUTOGENERATED_FINAL -->",
        "",
        "## 自动汇总的最终状态",
        "",
        f"- Gate 0：`{result['gate0_passed']}`；Gate 1：`{result['gate1_passed']}`；Gate 2/3 未运行。",
        f"- 实际研究更新：`{json.dumps(result['research_steps'])}`。",
        f"- 完整回归：`{json.dumps(result['regression_tests'])}`。",
        f"- 最终 AIP 独立检查：`{json.dumps(result['current_aip_tests'])}`。",
        f"- GPU 续训严格重放通过：`{result['gpu_resume']['passed']}`。",
        f"- 新旧参考缓存64帧全部值一致：`{result['reference_cache']['all_64_frame_values_equal']}`。",
        f"- 种子2复跑CSV完全相同：`{result['seed2_recheck']['all_csv_fields_equal']}`。",
        f"- 官方权重哈希未变：`{json.dumps(weights_equal)}`；受保护文件diff为空。",
        "",
        "原始结果、原检查点、失败重放证据均保留。此节由 scripts/aip_vtok/finalize.py 从 JSON/XML 生成。",
        "",
    ]
    log.write_text(prefix + "\n" + "\n".join(summary))
    print(
        json.dumps(
            {k: result[k] for k in ("gate0_passed", "gate1_passed", "regression_tests", "current_aip_tests")}
        )
    )


if __name__ == "__main__":
    main()
