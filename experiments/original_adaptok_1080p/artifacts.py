"""Atomic metadata and lossless RGB viewing artifacts, separate from model bitstreams."""

import csv
import json
import subprocess
from contextlib import contextmanager
from pathlib import Path

import numpy as np
from PIL import Image


@contextmanager
def exclusive_writer(directory):
    import fcntl

    Path(directory).mkdir(parents=True, exist_ok=True)
    with (Path(directory) / "experiment.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        yield


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".partial")
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False) + "\n")
    temporary.replace(path)


def write_csv(path, rows):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(dict.fromkeys(key for row in rows for key in row)), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def rgb_bytes(clip):
    return clip.detach().float().clamp(0, 1).mul(255).round().byte().permute(0, 2, 3, 1).cpu().contiguous().numpy()


def write_video(path, clip, fps):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    frames = rgb_bytes(clip)
    height, width = frames.shape[1:3]
    command = ["ffmpeg", "-v", "error", "-n", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{width}x{height}",
               "-r", str(fps), "-i", "pipe:0", "-an", "-c:v", "libx264rgb", "-crf", "0", "-preset", "veryfast", str(path)]
    subprocess.run(command, input=frames.tobytes(), check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)


def write_samples(path, original, recon):
    path = Path(path)
    path.mkdir(parents=True, exist_ok=True)
    original, recon = rgb_bytes(original[:1])[0], rgb_bytes(recon[:1])[0]
    Image.fromarray(original).save(path / "original.png")
    Image.fromarray(recon).save(path / "reconstructed.png")
    Image.fromarray(np.concatenate([original, recon], axis=1)).save(path / "comparison.png")
    # A fixed native 512x512 crop crossing both 128-pixel seams, without scaling.
    crop = np.concatenate([original[256:768, 640:1152], recon[256:768, 640:1152]], axis=1)
    Image.fromarray(crop).save(path / "boundary_crop.png")


def concatenate_videos(paths, destination):
    destination = Path(destination)
    listing = destination.with_suffix(".concat.txt")
    # Paths are generated by this experiment, never taken from a shell command.
    listing.write_text("".join("file '" + str(Path(p).resolve()).replace("'", "'\\''") + "'\n" for p in paths))
    subprocess.run(["ffmpeg", "-v", "error", "-n", "-f", "concat", "-safe", "0", "-i", str(listing),
                    "-c", "copy", str(destination)], check=True, capture_output=True)
